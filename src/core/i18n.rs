/// Localization helper service.
pub struct I18n;

impl I18n {
    /// Backward-compatible static get helper.
    #[inline(always)]
    pub fn get(lang: Language, key: TextKey) -> &'static str {
        Self::translate(lang, key)
    }

    /// Zero-allocation, O(1) table indexed translation.
    #[inline(always)]
    pub fn translate(lang: Language, key: TextKey) -> &'static str {
        let lang_idx = (lang as usize).min(TRANSLATIONS.len() - 1);
        let key_idx = key as usize;
        if key_idx < TRANSLATIONS[lang_idx].len() {
            TRANSLATIONS[lang_idx][key_idx]
        } else {
            TRANSLATIONS[0].first().copied().unwrap_or("")
        }
    }

    /// Locale-safe lowercase & diacritic search folding handling Turkish `İ`/`ı` -> `i`
    /// alongside Turkish/European diacritic folding and ASCII lowercase.
    pub fn fold_search_str(s: &str) -> String {
        let mut out = String::with_capacity(s.len());
        for ch in s.chars() {
            match ch {
                'İ' | 'I' | 'ı' | 'i' | 'î' | 'ï' | 'í' | 'Î' | 'Ï' | 'Í' => out.push('i'),
                'ş' | 'Ş' => out.push('s'),
                'ğ' | 'Ğ' => out.push('g'),
                'ü' | 'Ü' | 'û' | 'ú' | 'ù' | 'Û' | 'Ú' | 'Ù' => out.push('u'),
                'ö' | 'Ö' | 'ó' | 'ô' | 'ò' | 'Ó' | 'Ô' | 'Ò' => out.push('o'),
                'ç' | 'Ç' => out.push('c'),
                'ä' | 'à' | 'â' | 'á' | 'Ä' | 'À' | 'Â' | 'Á' => out.push('a'),
                'é' | 'è' | 'ê' | 'ë' | 'É' | 'È' | 'Ê' | 'Ë' => out.push('e'),
                'ñ' | 'Ñ' => out.push('n'),
                _ => {
                    for lower in ch.to_lowercase() {
                        if !matches!(lower, '\u{0300}'..='\u{036f}') {
                            out.push(lower);
                        }
                    }
                }
            }
        }
        out
    }
}

