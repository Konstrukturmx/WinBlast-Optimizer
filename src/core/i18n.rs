//! Zero-allocation internationalization (i18n) module for WinBlast0.
//!
//! Provides static table-indexed string lookups for 8 international languages:
//! English, Turkish, German, French, Spanish, Russian, Chinese, and Japanese.

use serde::{Deserialize, Serialize};

/// Supported interface languages.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[repr(u8)]
pub enum Language {
    #[default]
    English = 0,
    Turkish = 1,
    German = 2,
    French = 3,
    Spanish = 4,
    Russian = 5,
    Chinese = 6,
    Japanese = 7,
}

impl Language {
    /// Return the list of all available languages.
    #[allow(dead_code)]
    pub const ALL: [Language; 8] = [
        Language::English,
        Language::Turkish,
        Language::German,
        Language::French,
        Language::Spanish,
        Language::Russian,
        Language::Chinese,
        Language::Japanese,
    ];

    /// Human-readable native label for UI selector.
    pub const fn label(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Turkish => "Türkçe",
            Language::German => "Deutsch",
            Language::French => "Français",
            Language::Spanish => "Español",
            Language::Russian => "Русский",
            Language::Chinese => "简体中文",
            Language::Japanese => "日本語",
        }
    }

    /// Two-letter ISO language code.
    pub const fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Turkish => "tr",
            Language::German => "de",
            Language::French => "fr",
            Language::Spanish => "es",
            Language::Russian => "ru",
            Language::Chinese => "zh",
            Language::Japanese => "ja",
        }
    }
}

