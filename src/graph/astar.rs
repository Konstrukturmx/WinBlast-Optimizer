//! A* Goal-Driven Optimization Planner for WinBlast0 1.0.
//!
//! Uses A* heuristic search to find the optimal subset of tweaks that satisfies
//! the user's target performance, privacy, and stability goals while minimizing
//! disruption, risk, and reboot friction.

use std::cmp::Ordering;
use std::collections::{BinaryHeap, HashSet};

/// Target optimization goal for A* search.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OptimizationGoal {
    /// Friendly name of the goal profile (e.g., "Ultra Gaming Rig", "Stealth Privacy Fortress").
    pub name: String,
    /// Minimum desired performance gain score.
    pub min_perf_gain: u32,
    /// Minimum desired privacy protection score.
    pub min_privacy_gain: u32,
    /// Maximum acceptable risk level (0: Safe only, 1: Low, 2: Moderate, 3: High).
    pub max_risk_tolerance: u32,
    /// Whether tweaks requiring a system reboot are acceptable.
    pub allow_reboot: bool,
    /// Specific categories to prioritize.
    pub focus_categories: Vec<String>,
}

impl OptimizationGoal {
    pub fn ultra_gaming() -> Self {
        Self {
            name: "Ultra Gaming & Lowest Latency".to_string(),
            min_perf_gain: 25,
            min_privacy_gain: 5,
            max_risk_tolerance: 2, // Allow Moderate (e.g. ULPS, HAGS, Core Parking)
            allow_reboot: true,
            focus_categories: vec![
                "Hardware Tuning".to_string(),
                "GPU Tuning".to_string(),
                "Registry Lag".to_string(),
            ],
        }
    }

    pub fn stealth_privacy() -> Self {
        Self {
            name: "Stealth Privacy & Zero Telemetry".to_string(),
            min_perf_gain: 5,
            min_privacy_gain: 30,
            max_risk_tolerance: 1, // Safe & Low risk only
            allow_reboot: false,
            focus_categories: vec![
                "Privacy".to_string(),
                "Telemetry (OS)".to_string(),
                "Telemetry (Apps)".to_string(),
            ],
        }
    }

    pub fn balanced_daily() -> Self {
        Self {
            name: "Balanced Daily Driver".to_string(),
            min_perf_gain: 15,
            min_privacy_gain: 15,
            max_risk_tolerance: 0, // 100% Safe only
            allow_reboot: false,
            focus_categories: vec![
                "OS Settings".to_string(),
                "Bloatware".to_string(),
                "Privacy".to_string(),
            ],
        }
    }
}

/// A candidate tweak item available to the A* planner.
#[derive(Debug, Clone)]
pub struct TweakCandidate {
    pub id: String,
    pub category: String,
    pub perf_gain: u32,
    pub privacy_gain: u32,
    pub risk_weight: u32, // 0: Safe, 1: Low, 2: Moderate, 4: High
    pub requires_reboot: bool,
}

/// The output plan generated by A* search.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OptimizationPlan {
    pub goal_name: String,
    pub selected_tweak_ids: Vec<String>,
    pub achieved_perf_gain: u32,
    pub achieved_privacy_gain: u32,
    pub total_risk_score: u32,
    pub reboots_needed: usize,
    pub satisfied_goal: bool,
}

#[derive(Clone, Eq, PartialEq)]
struct AStarNode {
    /// Cost so far: risk + reboot penalties
    g_cost: u32,
    /// Estimated remaining distance to goal
    h_cost: u32,
    /// Index into tweak candidates
    candidate_idx: usize,
    /// Bitset or list of selected tweak indices
    selected: Vec<usize>,
    current_perf: u32,
    current_priv: u32,
    current_risk: u32,
    reboots: usize,
}

impl Ord for AStarNode {
    fn cmp(&self, other: &Self) -> Ordering {
        let self_f = self.g_cost + self.h_cost;
        let other_f = other.g_cost + other.h_cost;
        // Min-heap: lower f-cost has higher priority
        other_f.cmp(&self_f).then_with(|| other.g_cost.cmp(&self.g_cost))
    }
}

impl PartialOrd for AStarNode {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

#[derive(Debug, Clone, Default)]
pub struct AStarPlanner;

impl AStarPlanner {
    pub fn new() -> Self {
        Self
    }

    /// Run A* heuristic search to discover the optimal collection of tweaks
    /// that achieves `goal` with minimal cumulative risk and disruption.
    pub fn plan(
        &self,
        goal: &OptimizationGoal,
        candidates: &[TweakCandidate],
    ) -> OptimizationPlan {
        if candidates.is_empty() {
            return OptimizationPlan {
                goal_name: goal.name.clone(),
                selected_tweak_ids: Vec::new(),
                achieved_perf_gain: 0,
                achieved_privacy_gain: 0,
                total_risk_score: 0,
                reboots_needed: 0,
                satisfied_goal: false,
            };
        }

        // Filter candidates by hard constraints: risk tolerance and reboot permission
        let valid_candidates: Vec<&TweakCandidate> = candidates
            .iter()
            .filter(|c| {
                if c.risk_weight > goal.max_risk_tolerance {
                    return false;
                }
                if c.requires_reboot && !goal.allow_reboot {
                    return false;
                }
                true
            })
            .collect();

        if valid_candidates.is_empty() {
            return OptimizationPlan {
                goal_name: goal.name.clone(),
                selected_tweak_ids: Vec::new(),
                achieved_perf_gain: 0,
                achieved_privacy_gain: 0,
                total_risk_score: 0,
                reboots_needed: 0,
                satisfied_goal: false,
            };
        }

        let max_perf_step = valid_candidates.iter().map(|c| c.perf_gain).max().unwrap_or(1).max(1);
        let max_priv_step = valid_candidates.iter().map(|c| c.privacy_gain).max().unwrap_or(1).max(1);

        // Admissible heuristic function: lower bound on remaining steps to meet both targets
        let heuristic = |perf: u32, priv_score: u32| -> u32 {
            let perf_deficit = goal.min_perf_gain.saturating_sub(perf);
            let priv_deficit = goal.min_privacy_gain.saturating_sub(priv_score);
            let perf_steps = perf_deficit.div_ceil(max_perf_step);
            let priv_steps = priv_deficit.div_ceil(max_priv_step);
            // Weighted admissible estimate
            perf_steps.max(priv_steps) * 2
        };

        let mut open_set = BinaryHeap::new();
        let initial_h = heuristic(0, 0);

        open_set.push(AStarNode {
            g_cost: 0,
            h_cost: initial_h,
            candidate_idx: 0,
            selected: Vec::new(),
            current_perf: 0,
            current_priv: 0,
            current_risk: 0,
            reboots: 0,
        });

        let mut best_plan: Option<AStarNode> = None;
        let mut visited_states = HashSet::new();
        let max_iterations = 2500; // Fast bounded A* exploration
        let mut iterations = 0;

        while let Some(current) = open_set.pop() {
            iterations += 1;
            if iterations > max_iterations {
                break;
            }

            // Check if goal conditions are satisfied
            if current.current_perf >= goal.min_perf_gain && current.current_priv >= goal.min_privacy_gain {
                best_plan = Some(current);
                break;
            }

            // Track state signature: (perf, priv, candidate_idx)
            let state_sig = (current.current_perf, current.current_priv, current.candidate_idx);
            if visited_states.contains(&state_sig) {
                continue;
            }
            visited_states.insert(state_sig);

            if current.candidate_idx >= valid_candidates.len() {
                continue;
            }

            let candidate = valid_candidates[current.candidate_idx];

            // Branch 1: INCLUDE candidate tweak
            let mut incl_selected = current.selected.clone();
            incl_selected.push(current.candidate_idx);
            let next_perf = current.current_perf + candidate.perf_gain;
            let next_priv = current.current_priv + candidate.privacy_gain;
            let next_risk = current.current_risk + candidate.risk_weight;
            let next_reboots = current.reboots + (if candidate.requires_reboot { 1 } else { 0 });

            // Step cost: risk penalty + reboot friction
            let step_cost = 1 + candidate.risk_weight * 3 + (if candidate.requires_reboot { 5 } else { 0 });
            let next_g = current.g_cost + step_cost;
            let next_h = heuristic(next_perf, next_priv);

            open_set.push(AStarNode {
                g_cost: next_g,
                h_cost: next_h,
                candidate_idx: current.candidate_idx + 1,
                selected: incl_selected,
                current_perf: next_perf,
                current_priv: next_priv,
                current_risk: next_risk,
                reboots: next_reboots,
            });

            // Branch 2: EXCLUDE candidate tweak
            open_set.push(AStarNode {
                g_cost: current.g_cost,
                h_cost: current.h_cost,
                candidate_idx: current.candidate_idx + 1,
                selected: current.selected,
                current_perf: current.current_perf,
                current_priv: current.current_priv,
                current_risk: current.current_risk,
                reboots: current.reboots,
            });
        }

        // Return best plan found, or greedy fallback if bounds were tight
        if let Some(plan_node) = best_plan {
            let selected_ids = plan_node
                .selected
                .iter()
                .map(|&idx| valid_candidates[idx].id.clone())
                .collect();

            OptimizationPlan {
                goal_name: goal.name.clone(),
                selected_tweak_ids: selected_ids,
                achieved_perf_gain: plan_node.current_perf,
                achieved_privacy_gain: plan_node.current_priv,
                total_risk_score: plan_node.current_risk,
                reboots_needed: plan_node.reboots,
                satisfied_goal: true,
            }
        } else {
            // Greedy fallback: accumulate highest gain per cost items until max possible
            let mut greedy_selected = Vec::new();
            let mut p = 0;
            let mut pr = 0;
            let mut r = 0;
            let mut rb = 0;

            for candidate in &valid_candidates {
                if p >= goal.min_perf_gain && pr >= goal.min_privacy_gain {
                    break;
                }
                greedy_selected.push(candidate.id.clone());
                p += candidate.perf_gain;
                pr += candidate.privacy_gain;
                r += candidate.risk_weight;
                if candidate.requires_reboot {
                    rb += 1;
                }
            }

            OptimizationPlan {
                goal_name: goal.name.clone(),
                selected_tweak_ids: greedy_selected,
                achieved_perf_gain: p,
                achieved_privacy_gain: pr,
                total_risk_score: r,
                reboots_needed: rb,
                satisfied_goal: p >= goal.min_perf_gain && pr >= goal.min_privacy_gain,
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_astar_finds_optimal_gaming_path() {
        let planner = AStarPlanner::new();
        let goal = OptimizationGoal::ultra_gaming();

        let candidates = vec![
            TweakCandidate {
                id: "hags".to_string(),
                category: "Hardware Tuning".to_string(),
                perf_gain: 15,
                privacy_gain: 0,
                risk_weight: 1,
                requires_reboot: false,
            },
            TweakCandidate {
                id: "win32_priority".to_string(),
                category: "Registry Lag".to_string(),
                perf_gain: 12,
                privacy_gain: 0,
                risk_weight: 0,
                requires_reboot: false,
            },
            TweakCandidate {
                id: "disable_telemetry".to_string(),
                category: "Privacy".to_string(),
                perf_gain: 2,
                privacy_gain: 10,
                risk_weight: 0,
                requires_reboot: false,
            },
        ];

        let plan = planner.plan(&goal, &candidates);
        assert!(plan.satisfied_goal);
        assert!(plan.achieved_perf_gain >= goal.min_perf_gain);
        assert!(plan.selected_tweak_ids.contains(&"hags".to_string()));
        assert!(plan.selected_tweak_ids.contains(&"win32_priority".to_string()));
    }

    #[test]
    fn test_astar_respects_reboot_constraint() {
        let planner = AStarPlanner::new();
        let goal = OptimizationGoal::stealth_privacy(); // allow_reboot = false

        let candidates = vec![
            TweakCandidate {
                id: "heavy_reboot_tweak".to_string(),
                category: "Privacy".to_string(),
                perf_gain: 0,
                privacy_gain: 35,
                risk_weight: 0,
                requires_reboot: true, // Should be rejected
            },
            TweakCandidate {
                id: "instant_privacy_tweak_1".to_string(),
                category: "Privacy".to_string(),
                perf_gain: 0,
                privacy_gain: 20,
                risk_weight: 0,
                requires_reboot: false,
            },
            TweakCandidate {
                id: "instant_privacy_tweak_2".to_string(),
                category: "Privacy".to_string(),
                perf_gain: 5,
                privacy_gain: 15,
                risk_weight: 0,
                requires_reboot: false,
            },
        ];

        let plan = planner.plan(&goal, &candidates);
        assert!(plan.satisfied_goal);
        assert!(!plan.selected_tweak_ids.contains(&"heavy_reboot_tweak".to_string()));
        assert_eq!(plan.reboots_needed, 0);
    }
}
